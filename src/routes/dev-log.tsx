const TAGS: Tag[] = ["數據", "技術", "前端", "系統"];

function DevLogPage() {
  const [filter, setFilter] = useState<Tag | null>(null);
  const list = filter ? ENTRIES.filter((e) => e.tags.includes(filter)) : ENTRIES;

  return (
    <AppShell page="engine" ticker="開發者日誌 · 時間以香港時間（HKT）為準">
      <PageHead
        en="Changelog · Dev Log"
        title="開發者日誌"
        desc="天喜每次重大更新都記錄喺度：日期、時間同細節，全部公開可追溯。"
      />

      <div className="no-scrollbar mx-4 mb-1 flex gap-1.5 overflow-x-auto">
        <button
          type="button"
          onClick={() => setFilter(null)}
          className={`shrink-0 rounded-full border px-2.5 py-1 text-[11px] font-bold ${
            filter === null ? "border-gold-strong bg-gold-bg text-gold" : "border-hairline bg-paper text-ink-2"
          }`}
        >
          全部
        </button>
        {TAGS.map((t) => (
          <button
            key={t}
            type="button"
            onClick={() => setFilter(t)}
            className={`shrink-0 rounded-full border px-2.5 py-1 text-[11px] font-bold ${
              filter === t ? "border-gold-strong bg-gold-bg text-gold" : "border-hairline bg-paper text-ink-2"
            }`}
          >
            {t}
          </button>
        ))}
      </div>

      <Card title="更新記錄" en="Entries">
        <div className="divide-y divide-hairline">
          {list.map((e) => (
            <article key={e.title} className="py-3">
              <p className="tabnum font-mono-tx text-[10px] text-ink-3">{e.date}</p>
              <h3 className="mt-0.5 font-serif-tc text-[13px] font-bold text-ink">{e.title}</h3>
              <div className="mt-1 flex flex-wrap gap-1">
                {e.tags.map((t) => (
                  <Pill key={t}>{t}</Pill>
                ))}
              </div>
              <p className="mt-1.5 text-[12px] leading-relaxed text-ink-2">{e.body}</p>
            </article>
          ))}
        </div>
      </Card>

      <Disclaimer />
    </AppShell>
  );
}
